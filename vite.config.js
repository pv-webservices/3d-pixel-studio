import { defineConfig } from 'vite';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = import.meta.dirname;
const PARTIALS = resolve(root, 'src/partials');

// Static HTML includes: <!-- @include header --> pulls src/partials/header.html at build/dev time,
// so shared chrome stays in real HTML (crawlable) without a templating framework.
function htmlIncludes() {
  const include = (html, depth = 0) =>
    html.replace(/<!--\s*@include\s+([\w-]+)\s*-->/g, (_, name) => {
      if (depth > 4) throw new Error(`Include depth exceeded at "${name}"`);
      return include(readFileSync(resolve(PARTIALS, `${name}.html`), 'utf8'), depth + 1);
    });
  return {
    name: 'html-includes',
    transformIndexHtml: { order: 'pre', handler: (html) => responsiveImages(include(html)) },
    handleHotUpdate({ file, server }) {
      if (file.startsWith(PARTIALS)) server.ws.send({ type: 'full-reload' });
    },
  };
}

// <img data-m="exterior/slug" alt="…"> expands to src/srcset/width/height from the media manifest
// generated by `npm run media`. Add data-eager for above-the-fold (LCP) images.
function loadManifest() {
  const list = JSON.parse(readFileSync(resolve(root, 'src/data/media.json'), 'utf8'));
  return new Map(list.map((m) => [m.src.replace('/media/', ''), m]));
}

function responsiveImages(html) {
  const manifest = loadManifest();
  return html.replace(/<img([^>]*?)\sdata-m="([^"]+)"([^>]*)>/g, (tag, before, key, after) => {
    const m = manifest.get(key);
    if (!m) throw new Error(`Unknown media key "${key}" — run npm run media or fix the path`);
    const attrs = `${before}${after}`.replace(/\s*\/\s*$/, '');
    const eager = /\sdata-eager\b/.test(attrs);
    const fallback = m.sizes.filter((w) => w <= 1280).at(-1) ?? m.sizes[0];
    const srcset = m.sizes.map((w) => `${m.src}-${w}.webp ${w}w`).join(', ');
    const sizes = /\ssizes=/.test(attrs) ? '' : ' sizes="100vw"';
    const loading = eager ? ' fetchpriority="high"' : /\sloading=/.test(attrs) ? '' : ' loading="lazy" decoding="async"';
    const alt = /\salt=/.test(attrs) ? '' : ` alt="${m.alt}"`;
    return `<img${attrs.replace(/\sdata-eager\b/, '')} src="${m.src}-${fallback}.webp" srcset="${srcset}"${sizes} width="${m.w}" height="${m.h}"${alt}${loading}>`;
  });
}

const pages = {
  home: 'index.html',
  work: 'work/index.html',
  studio: 'studio/index.html',
  services: 'services/index.html',
  insights: 'insights/index.html',
  article: 'insights/why-interior-cgi-is-a-game-changer-for-modern-designers/index.html',
  review: 'project-review/index.html',
};

export default defineConfig({
  appType: 'mpa',
  publicDir: 'static',
  plugins: [htmlIncludes()],
  build: {
    outDir: 'dist',
    assetsInlineLimit: 0,
    rollupOptions: {
      input: Object.fromEntries(Object.entries(pages).map(([k, v]) => [k, resolve(root, v)])),
    },
  },
  server: { port: 5173, host: true },
});
